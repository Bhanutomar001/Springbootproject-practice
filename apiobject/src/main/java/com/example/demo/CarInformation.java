package com.example.demo;

public class CarInformation {
  public String name;
  public int myear;
  public String color;
  public String avacity;
  public String getAvacity() {
	return avacity;
}
  public void setAvacity(String avacity) {
	this.avacity = avacity;
  }
  public String getName() {
	return name;
  }
  public void setName(String name) {
	this.name = name;
  }
  public int getMyear() {
	return myear;
  }
  public void setMyear(int myear) {
	this.myear = myear;
  }
  public String getColor() {
	return color;
  }
  public void setColor(String color) {
	this.color = color;
}
}
